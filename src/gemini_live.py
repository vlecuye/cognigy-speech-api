"""Gemini Live streaming TTS client using the Gemini Live WebSocket API."""

import logging
from typing import AsyncGenerator, Callable, Optional
from src.config import Settings
from src.audio_utils import resample_pcm

logger = logging.getLogger(__name__)

SYNTHESIS_SYSTEM_INSTRUCTION = (
    "You are an ultra-low-latency text-to-speech engine. "
    "When given text, read it aloud verbatim with natural pacing and emotion. "
    "Never reply to the text, answer questions, or add conversational commentary."
)


class GeminiLiveClient:
    """Client for streaming voice synthesis via the Gemini Live API."""

    def __init__(self, settings: Settings, client_factory: Optional[Callable] = None):
        self.settings = settings
        self._client_factory = client_factory
        self._client = None

    @property
    def client(self):
        if self._client is None:
            if self._client_factory:
                self._client = self._client_factory()
            else:
                from google import genai
                self._client = genai.Client(
                    enterprise=True,
                    project=self.settings.project_id,
                    location=self.settings.location,
                )
        return self._client

    async def stream_speech(
        self,
        text: str,
        voice: Optional[str] = None,
        target_sample_rate: int = 8000,
        model: Optional[str] = None,
    ) -> AsyncGenerator[bytes, None]:
        """Stream resampled linear16 PCM chunks as they are generated by Gemini Live.

        - Connects to Gemini Live API over WebSocket
        - Sends verbatim text to speak
        - Iteratively yields resampled linear16 PCM chunks (e.g. 8000 Hz)
        """
        from google.genai import types

        voice_name = voice or self.settings.default_voice
        model_name = model or self.settings.live_tts_model

        config = types.LiveConnectConfig(
            response_modalities=[types.Modality.AUDIO],
            speech_config=types.SpeechConfig(
                voice_config=types.VoiceConfig(
                    prebuilt_voice_config=types.PrebuiltVoiceConfig(voice_name=voice_name)
                )
            ),
            system_instruction=types.Content(
                parts=[types.Part(text=SYNTHESIS_SYSTEM_INSTRUCTION)]
            ),
        )

        logger.info(
            "Connecting to Gemini Live API model=%s, voice=%s, text_len=%d",
            model_name,
            voice_name,
            len(text),
        )

        async with self.client.aio.live.connect(model=model_name, config=config) as session:
            # Send the text to speak
            await session.send_realtime_input(text=text)

            # Receive streaming audio chunks
            async for response in session.receive():
                server_content = response.server_content
                if not server_content:
                    continue

                if server_content.model_turn:
                    for part in server_content.model_turn.parts:
                        if part.inline_data and part.inline_data.data:
                            # Gemini Live outputs 24kHz 16-bit linear PCM
                            raw_chunk_24k = part.inline_data.data
                            resampled_chunk = resample_pcm(
                                raw_chunk_24k,
                                orig_rate=24000,
                                target_rate=target_sample_rate,
                            )
                            if resampled_chunk:
                                yield resampled_chunk

                if server_content.turn_complete:
                    logger.info("Gemini Live turn complete for text_len=%d", len(text))
                    break
